/**
 * 在关键点表上做 Catmull–Rom 插值（张力 0.5），得到任意高度的半宽。
 * 表按 y 递减排列，先二分定位区间，再用相邻四点做样条，保证 C¹ 连续。
 */
export function halfWidthAt(y: number): number {
  const n = PROFILE.length;
  if (y >= PROFILE[0][0]) return PROFILE[0][1];
  if (y <= PROFILE[n - 1][0]) return PROFILE[n - 1][1];

  let lo = 0;
  let hi = n - 1;
  while (hi - lo > 1) {
    const mid = (lo + hi) >> 1;
    if (PROFILE[mid][0] >= y) lo = mid;
    else hi = mid;
  }
  const i = lo;
  const y0 = PROFILE[i][0];
  const y1 = PROFILE[i + 1][0];
  const t = (y0 - y) / (y0 - y1);

  const p = (k: number): number => PROFILE[Math.max(0, Math.min(n - 1, k))][1];
  const p0 = p(i - 1);
  const p1 = p(i);
  const p2 = p(i + 1);
  const p3 = p(i + 2);

  const t2 = t * t;
  const t3 = t2 * t;
  const v =
    0.5 *
    (2 * p1 +
      (-p0 + p2) * t +
      (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2 +
      (-p0 + 3 * p1 - 3 * p2 + p3) * t3);

  return Math.max(0, v);
}

/**
 * 单位坐标半宽 → 参考片口径的「宽度 ÷ 体高」。
 * 供校验脚本对照实测值使用。
 */
export function normWidthOf(unitHalf: number): number {
  return (unitHalf * 2) / BODY_H;
}

/**
 * 横截面形状：人体不是正圆，而是**前后扁、左右宽**的椭圆。
 * depthRatio 给出「前后半深 ÷ 左右半宽」，按高度变化。
 *
 * ⚠️ 这里用**分段线性插值**而不是阶梯取值。
 * 早先是 `if (y >= 0.46) return 0.74;` 这样的阶梯函数，在 0.24 / 0.46 / 0.66
 * 三处高度上前后深度会**突然跳变**，从侧面看躯干侧面出现一圈圈台阶，
 * 像叠起来的桶。改成线性过渡后侧视轮廓是连续的。
 *
 * 数值口径（坐姿 + 盘腿，含胸，侧向本就比正面薄）：
 *   · 头部接近圆（0.90），头略深
 *   · 颈很细且接近圆（0.94）
 *   · 肩带 0.68 → 胸廓 0.58：胸腔前后薄、左右宽
 *   · 腰腹 0.62（坐姿腹部略厚）
 *   · 髋 0.58 → 盘腿 0.44：盘腿是一摊宽而低的土丘
 * 原值（肩 0.74 / 胸 0.64 / 腰 0.70 / 髋 0.64）整体偏厚，侧视渲染成鼓桶。
 */
const DEPTH_KEY: ReadonlyArray<readonly [number, number]> = [
  [0.98, 0.90],
  [0.78, 0.90], // 头
  [0.66, 0.94], // 颈
  // 肩带：**人体最厚的横截面之一**（肩胛 + 斜方肌 + 胸廓上口）。
  // 原给 0.68 太薄，正视角下肩部没有体积感，只剩一条线，
  // 渲染出来「没有肩」。提到 0.80 肩才立得起来。
  [0.46, 0.80],
  [0.24, 0.62], // 胸廓
  [0.06, 0.66], // 腰
  [-0.06, 0.62], // 髋
  // 盘腿：**必须比躯干扁得多**。
  // 盘腿的左右半宽是 0.55（膝在最外侧），若前后深度也按 0.44 给，
  // 得到的是一个「水平圆盘」——渲染出来就是人坐在一张飞碟上。
  // 真实盘腿坐的前后径只是左右宽的 0.28 左右（臀后凸 + 膝前伸）。
  [-0.46, 0.28],
];

export function depthRatioAt(y: number): number {
  const k = DEPTH_KEY;
  if (y >= k[0][0]) return k[0][1];
  const last = k[k.length - 1];
  if (y <= last[0]) return last[1];
  for (let i = 0; i < k.length - 1; i++) {
    const [y0, v0] = k[i];
    const [y1, v1] = k[i + 1];
    if (y <= y0 && y >= y1) {
      const t = y0 === y1 ? 0 : (y0 - y) / (y0 - y1);
      // smoothstep 过渡，避免折线拐点处出现可见折角
      const s = t * t * (3 - 2 * t);
      return v0 + (v1 - v0) * s;
    }
  }
  return last[1];
}

/** 采样层数：160 层在 1080p（人形高约 370px）下层距约 2.3px，足够平滑 */
export const SWEEP_STEPS = 160;

/**
 * 把剖面表采样成 `{ y, halfW, halfD }` 数组，供 3D 旋转体使用。
 *
 * @param scale 单位坐标 → 世界单位的倍率
 * @param steps 采样层数
 */
export function sampleProfile(
  scale = 1,
  steps = SWEEP_STEPS,
): Array<{ y: number; halfW: number; halfD: number }> {
  const out: Array<{ y: number; halfW: number; halfD: number }> = [];
  for (let i = 0; i <= steps; i++) {
    const t = i / steps;
    const y = HEAD_TOP - t * BODY_H;
    const halfW = halfWidthAt(y);
    out.push({
      y: (y - (HEAD_TOP + LAP_BOTTOM) / 2) * scale,
      halfW: halfW * scale,
      halfD: halfW * depthRatioAt(y) * scale,
    });
  }
  return out;
}
