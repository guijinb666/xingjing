/** 单字繁体 → 简体 */
export function toSimp(text: string): string {
  // 先尝试整词映射（长词优先），再逐字回退
  const direct = TRAD_TO_SIMP[text];
  if (direct) return direct;

  let out = '';
  for (const ch of text) {
    out += TRAD_TO_SIMP[ch] ?? ch;
  }
  return out;
}

/** 神煞名规范化为简体（规则表内部已用简体，此处做入口防御） */
export function normalizeShenShaName(name: string): string {
  return toSimp(name);
}

/** 十神名规范化为简体 */
export function normalizeShiShenName(name: string): string {
  return toSimp(name);
}

