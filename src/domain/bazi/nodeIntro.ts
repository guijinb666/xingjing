/**
 * 取一条介绍。
 *
 * 名称来自 `ChartNode.name`，可能是十神也可能是神煞；
 * 两者都查不到时返回 null，由调用方退回「无释义」的兜底呈现。
 */
export function introOf(name: string): NodeIntro | null {
  const shi = (SHI_SHEN_INTRO as Record<string, NodeIntro | undefined>)[name];
  if (shi) return shi;
  const sha = (SHEN_SHA_INTRO as Record<string, NodeIntro | undefined>)[name];
  if (sha) return sha;
  return null;
}

/** 该名称是十神还是神煞（用 ChartNode.group 更准，此处供纯名称场景兜底） */
export function isShiShenName(name: string): name is keyof ShiShenIntro {
  return Object.prototype.hasOwnProperty.call(SHI_SHEN_INTRO, name);
}

